/**
 * WP-CLI: `wp beltoft-cache purge`, `status`, `preload`, `purge-url` and `sweep` (the dedicated sweep runner).
 */
if ( defined( 'WP_CLI' ) && WP_CLI ) {
	WP_CLI::add_command(
		'beltoft-cache',
		static function ( $args, $assoc = array() ) {
			$sub = isset( $args[0] ) ? $args[0] : 'status';

			if ( 'purge' === $sub ) {
				WP_CLI::success( sprintf( 'Purged %d cached pages.', beltoft_cache_purge_all() ) );

				/*
				 * The purge queued a warm-up for the end of the request. On a web request that runs
				 * after the browser has been let go; on the shell there is nothing to let go, so run
				 * it here where the person watching can see what it did rather than after the last
				 * line has been printed.
				 */
				beltoft_cache_warm_on_shutdown();

				WP_CLI::line( 'Warm-up: ' . beltoft_cache_last_warm_summary() );

				return;
			}

			if ( 'sweep' === $sub ) {
				// For its own cron line: * * * * * wp beltoft-cache sweep --path=... --quiet
				$ran = beltoft_cache_sweep_run();
				WP_CLI::log( sprintf( 'Sweep batches run: %d. Queued: %s.', $ran, wp_json_encode( beltoft_cache_sweep_queue_get() ) ) );
				return;
			}

			if ( 'purge-url' === $sub ) {
				$url = isset( $args[1] ) ? esc_url_raw( $args[1] ) : '';

				if ( ! $url || ! beltoft_cache_purge_url( $url ) ) {
					WP_CLI::error( 'URL was invalid, not on the canonical host, or was not cached.' );
				}

				beltoft_cache_warm_url_after_response( $url );
				beltoft_cache_warm_on_shutdown();

				WP_CLI::success( 'Purged one cached page: ' . $url );

				return;
			}

			if ( 'preload' === $sub ) {
				$force  = ! empty( $assoc['force'] );
				$result = beltoft_cache_preload( $force );

				WP_CLI::line(
					sprintf(
						'Warmed %d, already warm %d, served from cache %d, failed %d, uncacheable %d - %ss.',
						$result['warmed'],
						$result['skipped'],
						$result['cached'],
						$result['failed'],
						$result['bypassed'],
						$result['seconds']
					)
				);

				if ( ! empty( $result['superseded'] ) ) {
					WP_CLI::warning( 'Something purged the cache mid-run, so this stopped early. That purge is warming the pages that matter itself.' );

					return;
				}

				if ( $result['cached'] > 0 ) {
					WP_CLI::warning( 'Some URLs answered HIT, so PHP never re-rendered them. Purge first if that was the intent.' );
				}

				if ( $result['bypassed'] > 0 ) {
					WP_CLI::warning( 'Some URLs came back BYPASS - the preload skip list and the nginx $skip_cache rules disagree.' );
				}

				if ( $result['failed'] > 0 ) {
					WP_CLI::warning( 'Some URLs did not return 200.' );
				}

				return;
			}

			$test  = beltoft_cache_self_test();
			$files = array_filter(
				(array) glob( BELTOFT_CACHE_DIR . '/*' ),
				static function ( $f ) {
					return preg_match( '/^[0-9a-f]{32}$/', basename( $f ) );
				}
			);
			$bytes = array_sum( array_map( 'filesize', $files ) );

			WP_CLI::line( 'Cache dir:  ' . BELTOFT_CACHE_DIR );
			WP_CLI::line( 'Key basis:  ' . BELTOFT_CACHE_KEY_SCHEME . BELTOFT_CACHE_KEY_METHOD . '<host><request_uri>' );
			WP_CLI::line( 'Entries:    ' . count( $files ) . ' (' . size_format( $bytes ) . ')' );
			WP_CLI::line( 'Key check:  ' . ( $test['ok'] ? 'OK' : 'FAILED' ) . ' - ' . $test['note'] );
			WP_CLI::line( 'Front page: ' . basename( beltoft_cache_file_for( home_url( '/' ) ) ) );

			$all  = beltoft_cache_preload_urls();
			$warm = 0;

			foreach ( $all as $url ) {
				if ( beltoft_cache_is_warm( $url ) ) {
					$warm++;
				}
			}

			WP_CLI::line( 'Warm:       ' . $warm . ' of ' . count( $all ) . ' preloadable URLs' );
			WP_CLI::line( 'Generation: ' . beltoft_cache_generation() );
			WP_CLI::line( 'Last warm:  ' . beltoft_cache_last_warm_summary() );

			if ( ! $test['ok'] ) {
				WP_CLI::warning( 'Purging will not work until the key matches the nginx config.' );
			}
		}
	);
}
