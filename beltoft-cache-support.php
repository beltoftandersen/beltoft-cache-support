<?php
/**
 * Plugin Name: Beltoft Cache Support
 * Description: Makes the header cart safe and correct under full-page caching: mirrors the cart count and subtotal into a readable cookie and paints them client-side, so every page can be cached as one shared copy.
 * Version:     1.3.1
 * Author:      beltoft.net
 * Requires PHP: 8.0
 *
 * WHY THIS EXISTS
 *
 * With an nginx page cache, one copy of each page is served to everyone. The header shows a
 * cart count and subtotal, so a naive setup either leaks one visitor's cart to the next or
 * has to bypass the cache for anyone shopping - which is precisely the audience whose page
 * views you most want cached.
 *
 * The split used here:
 *
 *   - nginx never STORES a response generated by someone holding a cart (fastcgi_no_cache on
 *     the Woo cart cookies), so the cached copy is always the cart-less one. That is the
 *     safety guarantee, and it is structural rather than a matter of getting a cookie list
 *     exactly right.
 *   - nginx still SERVES cached copies to people with carts (no bypass), so shoppers get
 *     cache hits. Their header is then filled in from a cookie by the script below.
 *
 * Those two are not redundant: the first is about what may enter the cache, the second about
 * what the visitor sees when they get a hit.
 *
 * WHY A COOKIE RATHER THAN WOO'S AJAX FRAGMENTS
 *
 * Fragments do arrive, but only after first paint - so the header would show 0 for a moment
 * on every cache hit. WooCommerce already publishes `woocommerce_items_in_cart` as a normal
 * readable cookie, which is enough for the count; it publishes only a HASH of the cart, so
 * the formatted subtotal has to be mirrored here. With both in cookies the header can be
 * painted during parse, before anything is drawn.
 *
 * Fragments are still welcome - they fill the dropdown's item list, which is hidden until
 * hover, and act as the correction if this cookie is ever stale.
 *
 * @package beltoft-cache-support
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

const BELTOFT_CACHE_COOKIE = 'beltoft_cart_summary';

/**
 * Mirror the cart count and formatted subtotal into a readable cookie.
 *
 * Hooked on `woocommerce_set_cart_cookies`, which is where WooCommerce sets its own cart
 * cookies - i.e. a point where headers have not been sent yet. Doing this later (on
 * `woocommerce_cart_updated`, say) risks "headers already sent".
 *
 * Deliberately NOT httpOnly: the whole point is that the front end can read it. It carries
 * no identity and nothing secret - a count and a price the visitor is already looking at.
 *
 * @param bool $set Whether WooCommerce is setting or clearing its cart cookies.
 */
add_action(
	'woocommerce_set_cart_cookies',
	static function ( $set ) {
		if ( ! function_exists( 'WC' ) || ! WC()->cart ) {
			return;
		}

		if ( ! $set || WC()->cart->is_empty() ) {
			beltoft_cache_clear_summary_cookie();

			return;
		}

		$count = (int) WC()->cart->get_cart_contents_count();

		/*
		 * get_cart_subtotal() returns markup; the cookie needs plain text. Entities have to
		 * be decoded as well as tags stripped: Woo writes the gap before "kr." as &nbsp;, and
		 * stripping tags alone leaves that entity as literal text - which then appears
		 * verbatim in the header, because the script sets textContent rather than innerHTML.
		 * The non-breaking space itself is kept, so the amount never wraps away from "kr.".
		 */
		$subtotal = html_entity_decode( wp_strip_all_tags( WC()->cart->get_cart_subtotal() ), ENT_QUOTES, 'UTF-8' );
		$subtotal = trim( $subtotal );

		/*
		 * "12|1.140,00 kr." - stored raw. setcookie() URL-encodes the value itself, so
		 * encoding the subtotal here too produced a double-encoded cookie that arrived in the
		 * browser as %2526nbsp%253B. One encoding, one decode.
		 */
		$value = $count . '|' . $subtotal;

		/*
		 * Arguments 4 and 5 are $secure and $httponly, in that order
		 * (wc_setcookie( $name, $value, $expire, $secure, $httponly )). Passing one `false`
		 * looked like it was saying "not httpOnly" - the comment above even claimed so - but it
		 * landed on $secure, so the cookie went out with no Secure attribute on an HTTPS-only
		 * site. Both are now explicit: Secure yes, httpOnly no.
		 *
		 * Expiry 0 (a session cookie) to match Woo's own woocommerce_items_in_cart, and that
		 * matters for correctness rather than tidiness: at 24h this cookie outlived the Woo
		 * cart cookies, and the only hook that clears it fires solely when
		 * woocommerce_items_in_cart is present. So a visitor who closed the browser and came
		 * back to an emptied cart kept a phantom count painted in the header.
		 */
		wc_setcookie( BELTOFT_CACHE_COOKIE, $value, 0, true, false );
	}
);

/**
 * Remove the cookie.
 *
 * @return void
 */
function beltoft_cache_clear_summary_cookie() {
	if ( ! isset( $_COOKIE[ BELTOFT_CACHE_COOKIE ] ) ) {
		return;
	}

	wc_setcookie( BELTOFT_CACHE_COOKIE, '', time() - HOUR_IN_SECONDS, true, false );
	unset( $_COOKIE[ BELTOFT_CACHE_COOKIE ] );
}

/**
 * Second, independent clear path: cookie present but the cart is actually empty.
 *
 * `woocommerce_set_cart_cookies` cannot be relied on to clear, because WooCommerce only fires
 * it with $set=false when woocommerce_items_in_cart happens to be present
 * (WC_Cart_Session::maybe_set_cart_cookies). Every other way a cart empties - a product
 * unpublished or deleted out from under it, a session expiring server-side, stock going away -
 * leaves this cookie behind, and the header then paints a count for an empty basket.
 *
 * Cheap: it does nothing at all unless the cookie is set, and cached page views never reach PHP.
 */
add_action(
	'template_redirect',
	static function () {
		if ( is_admin() || ! isset( $_COOKIE[ BELTOFT_CACHE_COOKIE ] ) ) {
			return;
		}

		if ( ! function_exists( 'WC' ) || ! WC()->cart ) {
			return;
		}

		if ( WC()->cart->is_empty() ) {
			beltoft_cache_clear_summary_cookie();
		}
	},
	5
);

/**
 * Paint the header cart from the cookie, before the browser paints.
 *
 * Printed inline in the head rather than enqueued: an external or deferred file executes
 * after the document has been parsed, which is exactly the flash of "0" this is meant to
 * remove. Inline and synchronous, it runs while the page is still being parsed.
 *
 * A MutationObserver is used because the header markup does not exist yet when this runs -
 * the observer paints each target the moment it appears, which for elements this early in
 * the document happens before first paint. `DOMContentLoaded` is a backstop for anything
 * that arrives late.
 *
 * Targets are WooCommerce's own fragment selectors, so this and the fragments agree on what
 * they are updating.
 */
add_action(
	'wp_head',
	static function () {
		if ( is_admin() ) {
			return;
		}

		$cookie = esc_js( BELTOFT_CACHE_COOKIE );

		/*
		 * Header count badges that only exist when the cart has items. The cached copy is the
		 * cart-less render, so such a badge is simply absent from it and there is no span to paint:
		 * the script creates it inside its fragment wrapper. Default: the Bricks header's mini-cart
		 * badge (dynamic fragment #brxe-mccntf holding text element #brxe-mccnt1, whose styling is
		 * keyed to that id in the header CSS). Fragments replace it with the real one after load.
		 */
		$badges = apply_filters(
			'beltoft_cache_count_badges',
			array( array( 'wrap' => '#brxe-mccntf', 'id' => 'brxe-mccnt1', 'class' => 'brxe-text-basic' ) )
		);
		?>
<script id="beltoft-cart-paint">
(function(){
	var NAME = '<?php echo $cookie; ?>';
	var BADGES = <?php echo wp_json_encode( array_values( (array) $badges ) ); ?>;

	function read(){
		var m = document.cookie.match(new RegExp('(?:^|; )' + NAME + '=([^;]*)'));
		if (!m) { return null; }
		/* One decode of the whole value - setcookie() encoded it once. */
		var parts = decodeURIComponent(m[1]).split('|');
		var count = parseInt(parts[0], 10);
		if (isNaN(count) || count < 1) { return null; }
		/* Trimmed HERE, with JS semantics, so the value written is byte-identical to the value
		   the guard above compares against. */
		return { count: count, subtotal: (parts[1] || '').trim() };
	}

	var cart = read();
	if (!cart) { return; }   /* no cart: the cached 0 is already correct */

	var done = { count: 0, subtotal: 0 };

	function paint(){
		BADGES.forEach(function(b){
			document.querySelectorAll(b.wrap).forEach(function(wrap){
				var el = wrap.querySelector('#' + b.id);
				/* Create only once the parser is past the wrapper (it has a next sibling, or parsing is done).
				   Earlier, on a page rendered WITH the real badge, the observer could fire before the real
				   child was parsed and the page ended up with two. */
				if (!el && (wrap.nextSibling || document.readyState !== 'loading')) { el = document.createElement('div'); el.id = b.id; el.className = b.class; wrap.appendChild(el); }
				if (!el) { return; }
				/* Same guard as below: write only on a real difference, or the observer loops. */
				if (el.textContent !== String(cart.count)) { el.textContent = cart.count; }
				done.count++;
			});
		});
		document.querySelectorAll('span.cart-count').forEach(function(el){
			if (el.textContent !== String(cart.count)) { el.textContent = cart.count; }
			done.count++;
		});
		if (cart.subtotal) {
			/* Compare and assign the SAME string. Reading with .trim() while writing the
			   untrimmed value would make every paint a fresh mutation whenever the two differ
			   by edge whitespace - and they can: PHP's trim() strips only ASCII space, while
			   this value deliberately keeps Woo's non-breaking space, which JS trim() DOES
			   strip. Since the observer below reacts to the write, that asymmetry is an
			   infinite microtask loop that pegs the tab rather than a cosmetic bug. */
			document.querySelectorAll('span.cart-subtotal').forEach(function(el){
				if (el.textContent.trim() !== cart.subtotal) { el.textContent = cart.subtotal; }
				done.subtotal++;
			});
		}
	}

	paint();

	var obs = new MutationObserver(paint);
	obs.observe(document.documentElement, { childList: true, subtree: true });

	document.addEventListener('DOMContentLoaded', function(){
		paint();
		/* Stop observing once the document is built; fragments own it from here. */
		obs.disconnect();
	});
})();
</script>
		<?php
	},
	1
);

/*
 * =============================================================================================
 * THE LOGIN NONCE IN CACHED HTML
 *
 * WooCommerce ties every nonce whose action starts with "woocommerce" to the guest's session id
 * (WC_Session_Handler::maybe_update_nonce_user_logged_out). A cached page was rendered for a
 * visitor with no session, so its login form carries a nonce built from uid 0 - but the moment a
 * visitor has a WC session, which any cart creates, wp_verify_nonce() computes with their session
 * id instead and rejects it.
 *
 * WooCommerce's process_login() checks that nonce before doing anything, and returns silently when
 * it fails. So a customer with something in their basket could not log in from the header form on
 * any cached page: no error, no redirect, the page simply reloaded. Verified with a probe -
 * identical nonce, verify=1 with no session cookie and verify=false with one.
 *
 * The alternatives were worse. Excluding session holders from the cache means every shopper browses
 * uncached from their first add-to-cart, which is the traffic worth caching and the reason the
 * cart-summary cookie exists. Unscoping the nonce would hand every guest the same login nonce for
 * up to 24h, re-enabling login-CSRF that WooCommerce added this scoping to prevent.
 *
 * So the form asks for a nonce belonging to ITS OWN session, at the moment of submitting. This
 * route is under /wp-json/, which $skip_cache already excludes, so the answer is never a cached
 * one. It hands the caller a nonce for their own session and nothing else - exactly what rendering
 * the page uncached would have given them.
 * =============================================================================================
 */
add_action(
	'rest_api_init',
	static function () {
		register_rest_route(
			'beltoft/v1',
			'/login-nonce',
			array(
				'methods'  => 'GET',
				// Public by design: a nonce for the caller's own session is not a secret, and this
				// is only reachable by someone already able to load the login form.
				'permission_callback' => '__return_true',
				'callback' => static function () {
					/*
					 * Load the WooCommerce session first, or this returns the very nonce it is
					 * supposed to replace.
					 *
					 * WooCommerce does not initialise its session on ordinary REST requests, so
					 * has_session() was false, maybe_update_nonce_user_logged_out() fell through to
					 * uid 0, and the route handed back a byte-identical copy of the stale nonce from
					 * the cached page. The fetch worked, the patch worked, and the login still
					 * failed - which looked exactly like the JS not running.
					 */
					if ( function_exists( 'wc_load_cart' ) && function_exists( 'WC' ) ) {
						if ( ! WC()->session || ! WC()->session->has_session() ) {
							wc_load_cart();
						}
					}

					return rest_ensure_response(
						array( 'nonce' => wp_create_nonce( 'woocommerce-login' ) )
					);
				},
			)
		);
	}
);

/*
 * =============================================================================================
 * PURGING
 *
 * nginx here is built without ngx_cache_purge, so there is no purge URL to call. What there is
 * instead is the cache directory, and the fact that nginx names every entry after the md5 of
 * its cache key. Deleting the file is a purge: nginx finds nothing on disk and regenerates.
 *
 * That makes this code entirely dependent on two things in
 * the site's nginx vhost matching the value below. On this installation:
 *
 *     fastcgi_cache_path /var/www/cache/staging.mindthetrash.pt keys_zone=STAGING_MTT:...;
 *     fastcgi_cache_key  "$scheme$request_method$host$request_uri";
 *
 * Change either and purging silently stops working - pages would just go stale for 12h rather
 * than erroring, which is the kind of failure nobody notices. `wp beltoft-cache status` exists
 * to make it checkable, and beltoft_cache_self_test() proves the key derivation against a file
 * nginx actually wrote.
 *
 * Note the scheme is "http", not "https". TLS is terminated by the upstream proxy and this
 * nginx listens on port 80, so $scheme is http in the key even though every public URL is
 * https. Deriving it from home_url() would produce keys that never match anything.
 * =============================================================================================
 */

/*
 * Keep each installation in its own cache directory. ABSPATH is used instead
 * of home_url() because this WordPress install serves a second B2B hostname,
 * while its filesystem directory remains the canonical cache owner. A server
 * with a different layout can define BELTOFT_CACHE_DIR in wp-config.php.
 */
if ( ! defined( 'BELTOFT_CACHE_DIR' ) ) {
	define( 'BELTOFT_CACHE_DIR', '/var/www/cache/' . basename( rtrim( ABSPATH, '/\\' ) ) );
}

/*
 * These values mirror the active Nginx directive:
 *
 *     fastcgi_cache_key "$scheme$request_method$host$request_uri";
 *
 * TLS terminates upstream, so this server sees `http` even though public URLs are HTTPS.
 * Keep the values overrideable from wp-config.php and expose them through the status command;
 * that makes a key change deliberate and detectable instead of an invisible purge failure.
 */
if ( ! defined( 'BELTOFT_CACHE_KEY_SCHEME' ) ) {
	define( 'BELTOFT_CACHE_KEY_SCHEME', 'http' );
}

if ( ! defined( 'BELTOFT_CACHE_KEY_METHOD' ) ) {
	define( 'BELTOFT_CACHE_KEY_METHOD', 'GET' );
}

/** Return the stored retail home, not the host-filtered B2B request URL. */
function beltoft_cache_canonical_home_url() {
	if ( class_exists( 'BeltoftCommerce\\Domain\\UrlFilter' ) ) {
		return BeltoftCommerce\Domain\UrlFilter::canonical();
	}

	return (string) get_option( 'home' );
}

/**
 * The on-disk filename nginx would use for a URL on this site.
 *
 * @param string $url Absolute or root-relative URL.
 * @return string Absolute path, whether or not it exists.
 */
function beltoft_cache_file_for( $url ) {
	$parts = wp_parse_url( $url );
	$path  = isset( $parts['path'] ) ? $parts['path'] : '/';
	$host  = wp_parse_url( beltoft_cache_canonical_home_url(), PHP_URL_HOST );

	// The B2B hostname is deliberately never in this cache. Do not let a manual purge
	// accidentally map a B2B URL onto the retail cache entry for the same path.
	if ( ! empty( $parts['host'] ) && strtolower( $parts['host'] ) !== strtolower( $host ) ) {
		return false;
	}

	// $request_uri includes the query string, so the key must too.
	if ( ! empty( $parts['query'] ) ) {
		$path .= '?' . $parts['query'];
	}

	$key = BELTOFT_CACHE_KEY_SCHEME . BELTOFT_CACHE_KEY_METHOD . $host . $path;

	return BELTOFT_CACHE_DIR . '/' . md5( $key );
}

/**
 * Purge one URL.
 *
 * @param string $url URL to purge.
 * @return bool True if an entry was removed.
 */
function beltoft_cache_purge_url( $url ) {
	$file = beltoft_cache_file_for( $url );

	if ( ! $file ) {
		return false;
	}

	// file_exists() rather than is_readable(): nginx writes these 0600 www-data, so PHP - as
	// the pool user - cannot read them. It can still stat and unlink them, because that only
	// needs write+execute on the directory.
	return file_exists( $file ) && @unlink( $file ); // phpcs:ignore WordPress.PHP.NoSilentErrors
}

/**
 * Purge everything.
 *
 * The whole cache rather than the edited page, deliberately: this site has 27 cacheable posts,
 * so a full flush costs one PHP render each on next visit, and it removes an entire class of
 * bug - the front page still showing an old product name, an archive missing a new dish, the
 * menu unchanged in the header of every other page. Working out which pages embed a given
 * post is the kind of thing that is right until someone adds a query loop somewhere.
 *
 * Only 32-hex filenames are touched, so nothing else that ends up in the directory is at risk.
 *
 * @return int Number of entries removed.
 */
function beltoft_cache_purge_all() {
	if ( ! is_dir( BELTOFT_CACHE_DIR ) ) {
		return 0;
	}

	$removed = 0;

	foreach ( (array) glob( BELTOFT_CACHE_DIR . '/*' ) as $file ) {
		if ( ! preg_match( '/^[0-9a-f]{32}$/', basename( $file ) ) ) {
			continue;
		}

		if ( @unlink( $file ) ) { // phpcs:ignore WordPress.PHP.NoSilentErrors
			$removed++;
		}
	}

	/*
	 * Every purge is a new generation, and every purge arranges its own warm-up. Doing both here
	 * rather than at each call site means there is no way to empty the cache and forget to refill
	 * it - the admin bar button, a Bricks save, a product update and WP-CLI all arrive through this
	 * one function.
	 *
	 * Deliberately takes no arguments: several of the hooks below pass an id as the first argument,
	 * and a parameter here would quietly collect menu and comment ids. The post being saved is
	 * handed over separately by the hooks that genuinely have one.
	 */
	beltoft_cache_bump_generation();
	beltoft_cache_warm_after_response();
	beltoft_cache_schedule_sweep();

	return $removed;
}

/**
 * Is the key derivation still in step with nginx?
 *
 * Takes a filename nginx wrote and checks that some public URL on this site hashes to it. If
 * the cache key or path in the nginx config is changed, this fails - which is the only cheap
 * warning available, since a mismatch otherwise just looks like "pages are stale".
 *
 * @return array{ok:bool,checked:int,note:string}
 */
function beltoft_cache_self_test() {
	$files = (array) glob( BELTOFT_CACHE_DIR . '/*' );
	$names = array();

	foreach ( $files as $file ) {
		if ( preg_match( '/^[0-9a-f]{32}$/', basename( $file ) ) ) {
			$names[ basename( $file ) ] = true;
		}
	}

	if ( ! $names ) {
		return array(
			'ok'      => true,
			'checked' => 0,
			'note'    => 'cache is empty - nothing to check against',
		);
	}

	$urls = array( home_url( '/' ) );

	foreach ( get_posts( array( 'post_type' => array( 'page', 'product' ), 'posts_per_page' => 40, 'fields' => 'ids' ) ) as $id ) {
		$urls[] = get_permalink( $id );
	}

	foreach ( $urls as $url ) {
		if ( isset( $names[ basename( beltoft_cache_file_for( $url ) ) ] ) ) {
			return array(
				'ok'      => true,
				'checked' => count( $names ),
				'note'    => 'key matches a cached entry (' . $url . ')',
			);
		}
	}

	return array(
		'ok'      => false,
		'checked' => count( $names ),
		'note'    => 'no public URL hashes to any cached file - fastcgi_cache_key or fastcgi_cache_path has probably changed',
	);
}

/*
 * =============================================================================================
 * PRELOAD - warm the cache back up after a purge, at a pace the server can absorb.
 *
 * Without this, the first visitor to each page after any content save pays the full PHP render
 * (~400ms instead of ~40ms), and since a purge is a FULL flush, one edit means 27 cold pages.
 * The warm-up is what makes full-flush-on-save affordable.
 *
 * TRIGGERED, NOT SCHEDULED. The purge itself starts the warm-up, in the same request: WordPress
 * sends the response, fastcgi_finish_request() hands the browser back to the editor, and the
 * worker that is already awake spends its last few seconds warming. Nothing is queued, so there
 * is no window in which the cache is cold and nobody has noticed yet.
 *
 * WHAT IT WARMS. The purge is still a full flush - safe, and never wrong about what changed -
 * but the warm-up is not. It fetches the front page, the shop archive and the page that was
 * actually edited: about five seconds of one worker rather than the forty a full 27-URL sweep
 * takes. The remaining pages warm on their first visit, exactly as they did before any of this
 * existed. Spending a worker on all 27 to save the twenty-eighth visitor 350ms is not a trade
 * worth making on a five-worker pool. `wp beltoft-cache preload` still sweeps everything when
 * somebody explicitly asks for it.
 *
 * PACED, and that is the standing design constraint. This pool is pm.max_children = 5, so a
 * warm-up that fired every URL at once would occupy every PHP worker and real visitors would
 * queue behind it - a cache making the site slower on exactly the requests that matter. So:
 * strictly one request at a time, a deliberate gap between them, a hard cap on how many URLs
 * and how many seconds one run may take. Never more than one of the five workers is in use.
 *
 * SUPERSESSION INSTEAD OF A LOCK. Every purge bumps a generation counter; a run captures it and
 * re-reads it between URLs, and stops the moment it changes. Save twice in a row and the first
 * warm-up stands down mid-flight, because whatever it warms from that point on is built from
 * content the second save has already replaced - and the request that bumped the counter is
 * warming the same pages with the newer content anyway.
 *
 * This replaces a ten-minute "is a preload running" transient, and the reason is worth keeping:
 * that lock had to be RELEASED, so a run killed by a dropped connection left it behind and every
 * warm-up for the next ten minutes did nothing while reporting nothing was needed. A counter has
 * no release step. A run that dies simply stops existing, and the next purge is unaffected.
 *
 * Already-warm URLs are skipped by checking for the file nginx would have written, so a run
 * with nothing to do costs a few stat() calls and no HTTP at all.
 * =============================================================================================
 */

/**
 * nginx serves an entry for fastcgi_cache_valid (12h) but keeps the file until `inactive` (24h). An
 * expired file still on disk is NOT warm: the next visitor gets a full render. Keep in step with the vhost.
 */
if ( ! defined( 'BELTOFT_CACHE_TTL' ) ) {
	define( 'BELTOFT_CACHE_TTL', 12 * HOUR_IN_SECONDS );
}

/**
 * Is this URL served from the cache right now (stored, and not yet expired)?
 *
 * @param string $url URL.
 * @return bool
 */
function beltoft_cache_is_warm( $url ) {
	$file = beltoft_cache_file_for( $url );

	// 60 s of headroom so a page about to expire is refreshed rather than skipped.
	return $file && file_exists( $file ) && filemtime( $file ) > time() - BELTOFT_CACHE_TTL + 60;
}

/** Legacy recurring hook. Kept only so a leftover scheduled event can be cleared. */
const BELTOFT_CACHE_PRELOAD_HOOK = 'beltoft_cache_preload_event';

/** Bumped by every purge. A warm-up that sees this change mid-run has been superseded. */
const BELTOFT_CACHE_GENERATION_OPTION = 'beltoft_cache_generation';

/** What the last warm-up did, so "why is my page still slow" is an answerable question. */
const BELTOFT_CACHE_LAST_WARM_OPTION = 'beltoft_cache_last_warm';

/** Gap between requests, microseconds. One worker, used politely. */
const BELTOFT_CACHE_PRELOAD_GAP = 1500000;

/** Most URLs one run may fetch, and the longest it may take. Runaway guards, not targets. */
const BELTOFT_CACHE_PRELOAD_MAX     = 60;
const BELTOFT_CACHE_PRELOAD_SECONDS = 150;

/**
 * The background sweep after a full purge (see beltoft_cache_schedule_sweep()). It runs from the
 * system cron under WP-CLI, so PHP-FPM's 120s request limit does not apply; these are runaway
 * guards for ONE batch: the sweep runs inside the shared every-minute cron runner, so a long run would hold
 * back other due events (follow-up emails, order cleanup) - each batch is short and queues the next one.
 */
const BELTOFT_CACHE_SWEEP_HOOK    = 'beltoft_cache_sweep_event';
const BELTOFT_CACHE_SWEEP_DELAY   = 60;
const BELTOFT_CACHE_SWEEP_MAX     = 20;
const BELTOFT_CACHE_SWEEP_SECONDS = 25;
const BELTOFT_CACHE_SWEEP_TIMEOUT = 10;

/**
 * Paths nginx refuses to cache, so preloading them would be pure waste.
 *
 * Deliberately the same pattern as $skip_cache in the vhost. If one changes and the other does
 * not, the symptom is a warm-up that spends its budget on pages that can never be stored.
 */
const BELTOFT_CACHE_PRELOAD_SKIP = '#^/(?:carrinho-de-compras|finalizar|a-minha-conta|wishlist|registar|iniciar|senha-perdida|redefinir-senha|entrar|registo|conta|encomenda-rapida|finalizar-b2b|conta-b2b|b2b-[^/]+)(?:/|$)#i';

/**
 * The current generation.
 *
 * Deliberately reads past the object cache. The whole point of this number is to notice a write
 * made by a DIFFERENT PHP process, and Redis keeps a request-local copy of what this process has
 * already read - so a warm-up polling it in a loop would sit there re-reading its own snapshot and
 * never learn it had been superseded. One Redis round trip between URLs, against a 1.5s gap.
 *
 * @return int
 */
function beltoft_cache_generation() {
	wp_cache_delete( BELTOFT_CACHE_GENERATION_OPTION, 'options' );

	return (int) get_option( BELTOFT_CACHE_GENERATION_OPTION, 0 );
}

/**
 * Move to the next generation. Called by every purge, and by nothing else.
 *
 * Stored with autoload off: it is read on the handful of requests that purge or warm, never on the
 * ones that serve a page, and an autoloaded option is fetched on all of them.
 *
 * @return int The new generation.
 */
function beltoft_cache_bump_generation() {
	$next = beltoft_cache_generation() + 1;

	update_option( BELTOFT_CACHE_GENERATION_OPTION, $next, false );

	return $next;
}

/**
 * Drop URLs nginx would refuse to store, so a warm-up cannot spend its budget on them.
 *
 * @param string[] $urls Candidate URLs.
 * @return string[] Unique, in the order given.
 */
function beltoft_cache_filter_urls( array $urls ) {
	$keep = array();

	foreach ( $urls as $url ) {
		if ( ! is_string( $url ) || '' === $url ) {
			continue;
		}

		$path = (string) wp_parse_url( $url, PHP_URL_PATH );

		// A query string is never cached either (see $is_args in the vhost).
		if ( preg_match( BELTOFT_CACHE_PRELOAD_SKIP, $path ) || wp_parse_url( $url, PHP_URL_QUERY ) ) {
			continue;
		}

		$keep[ $url ] = true;
	}

	return array_keys( $keep );
}

/**
 * The post types that are worth having in the page cache.
 *
 * One list, used both by the full sweep and by the after-a-save warm-up, so the two can never
 * disagree about what counts as a page. Anything else - templates, revisions, order records - has
 * no visitor to be fast for.
 *
 * @return string[]
 */
function beltoft_cache_preload_post_types() {
	return array( 'product', 'page' );
}

/**
 * The pages worth a worker's time the instant something is saved.
 *
 * Three at most: the front page and the shop archive, because between them they take most of the
 * traffic, plus whatever was just edited - which is the page the person who saved is about to
 * reload, and the one most likely to be linked from wherever they announce the change.
 *
 * @param int $post_id The post that triggered the purge, if a post did.
 * @return string[]
 */
function beltoft_cache_priority_urls( $post_id = 0 ) {
	$urls = array( home_url( '/' ) );

	if ( function_exists( 'wc_get_page_id' ) ) {
		$shop = (int) wc_get_page_id( 'shop' );

		if ( $shop > 0 ) {
			$urls[] = get_permalink( $shop );
		}
	}

	/*
	 * Only if it is a page a customer could actually land on.
	 *
	 * Two conditions, each for its own reason. Published, because warming something just trashed
	 * asks nginx to store a 404 behind a URL that looks perfectly ordinary. And one of the types
	 * the full sweep would warm anyway - because saving the footer in Bricks purges the cache, and
	 * a bricks_template is "viewable" enough to have a permalink like /template/footer/. That URL
	 * answers 200, so nothing looked broken; it just spent one of three priority slots warming a
	 * page nobody visits, and put it in the cache.
	 */
	if ( $post_id > 0
		&& 'publish' === get_post_status( $post_id )
		&& in_array( get_post_type( $post_id ), beltoft_cache_preload_post_types(), true ) ) {
		$urls[] = get_permalink( $post_id );
	}

	return beltoft_cache_filter_urls( $urls );
}

/**
 * Every URL worth having warm, most valuable first. Used by the explicit CLI sweep and by status.
 *
 * Ordered so that if a run hits its budget, what it managed to warm is what visitors are most
 * likely to ask for next: front page, then the archive, then the dishes, then everything else.
 *
 * @return string[]
 */
function beltoft_cache_preload_urls() {
	$urls = array( home_url( '/' ) );

	if ( function_exists( 'wc_get_page_id' ) ) {
		$shop = (int) wc_get_page_id( 'shop' );

		if ( $shop > 0 ) {
			$urls[] = get_permalink( $shop );
		}
	}

	// Pages first (few, high traffic), then the category and brand archives, then every visible product,
	// best sellers first - so a sweep cut short by a newer purge has already warmed what matters most.
	foreach ( get_posts( array( 'post_type' => 'page', 'post_status' => 'publish', 'posts_per_page' => 200, 'fields' => 'ids', 'orderby' => 'menu_order title', 'order' => 'ASC', 'suppress_filters' => true ) ) as $id ) {
		$urls[] = get_permalink( $id );
	}

	foreach ( array( 'product_cat', 'product_brand' ) as $tax ) {
		if ( ! taxonomy_exists( $tax ) ) {
			continue;
		}
		foreach ( (array) get_terms( array( 'taxonomy' => $tax, 'hide_empty' => true ) ) as $term ) {
			if ( $term instanceof WP_Term ) {
				$link = get_term_link( $term );
				if ( is_string( $link ) ) {
					$urls[] = $link;
				}
			}
		}
	}

	if ( in_array( 'product', beltoft_cache_preload_post_types(), true ) ) {
		$ids = get_posts(
			array(
				'post_type'        => 'product',
				'post_status'      => 'publish',
				'posts_per_page'   => -1,
				'fields'           => 'ids',
				'meta_key'         => 'total_sales', // phpcs:ignore WordPress.DB.SlowDBQuery
				'orderby'          => array( 'meta_value_num' => 'DESC', 'ID' => 'ASC' ), // ID: stable order for the sweep's cursor
				'suppress_filters' => true,
				'tax_query'        => array( array( 'taxonomy' => 'product_visibility', 'field' => 'name', 'terms' => array( 'exclude-from-catalog' ), 'operator' => 'NOT IN' ) ), // phpcs:ignore WordPress.DB.SlowDBQuery
			)
		);
		foreach ( $ids as $id ) {
			$urls[] = get_permalink( $id );
		}
	}

	return beltoft_cache_filter_urls( $urls );
}

/**
 * Fetch the URLs that are not already cached, one at a time, until something supersedes us.
 *
 * @param bool          $force   Re-fetch even URLs that are already warm.
 * @param string[]|null $urls    URLs to warm. Null means every preloadable URL on the site.
 * @param int           $max     Most URLs this run may fetch.
 * @param int           $seconds Longest this run may take.
 * @return array{warmed:int,skipped:int,failed:int,bypassed:int,cached:int,superseded:bool,seconds:float,urls:int}
 */
function beltoft_cache_preload( $force = false, $urls = null, $max = BELTOFT_CACHE_PRELOAD_MAX, $seconds = BELTOFT_CACHE_PRELOAD_SECONDS, $timeout = 20, $record = true ) {
	$started    = microtime( true );
	$generation = beltoft_cache_generation();
	$list       = null === $urls ? beltoft_cache_preload_urls() : array_values( (array) $urls );

	$out = array(
		'warmed'     => 0,
		'skipped'    => 0,
		'failed'     => 0,
		'bypassed'   => 0,
		'cached'     => 0,
		'superseded' => false,
		'urls'       => count( $list ),
		'scope'      => null === $urls ? 'all' : 'priority',
		'seconds'    => 0.0,
		'next'       => count( $list ), // index of the first URL this run did not get to (the sweep's cursor)
	);

	$fetched = 0;

	foreach ( $list as $index => $url ) {
		if ( $fetched >= $max
			|| ( microtime( true ) - $started ) > $seconds ) {
			$out['next'] = $index;
			break;
		}

		/*
		 * Somebody purged again while this run was in flight. Everything warmed from here on would
		 * be built from content that has already been replaced, and the request that bumped the
		 * counter is warming these same pages with the newer version. Stand down.
		 *
		 * Checked before the first URL as well, because a save can land in the gap between the
		 * response being sent and this loop starting.
		 */
		if ( beltoft_cache_generation() !== $generation ) {
			$out['superseded'] = true;

			break;
		}

		if ( $force ) {
			/*
			 * Purge before requesting, or --force cannot do anything at all. Skipping the
			 * warmth check is not enough: nginx still holds the entry, an anonymous
			 * cookie-less GET matches no bypass condition, so every "forced" request came
			 * back X-Cache: HIT, PHP was never re-entered, and the command still reported
			 * "Warmed 21" - success for work it had not done. That is worse than failing,
			 * because it is used exactly when someone is trying to fix a stale page.
			 */
			beltoft_cache_purge_url( $url );
		} elseif ( beltoft_cache_is_warm( $url ) ) {
			$out['skipped']++;

			continue;
		}

		if ( $fetched > 0 ) {
			usleep( BELTOFT_CACHE_PRELOAD_GAP );
		}

		$fetched++;

		/*
		 * The User-Agent is not cosmetic. This server blocks common bot and library agents,
		 * and the block answers with a 502 rather than a 403 - so a warm-up sending WordPress'
		 * default "WordPress/6.x; https://..." agent would appear to fail against a perfectly
		 * healthy site, and the cache would silently never warm. Same trap as curl here.
		 *
		 * No cookies are sent, so this render is anonymous: nothing to leak into the cache,
		 * and it cannot start a WooCommerce session.
		 */
		$response = wp_remote_get(
			$url,
			array(
				'timeout'     => $timeout,
				'redirection' => 0,
				'blocking'    => true,
				'sslverify'   => true,
				'user-agent'  => 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
				'headers'     => array(
					'Accept'          => 'text/html,application/xhtml+xml',
					'Accept-Language' => 'pt-PT,pt;q=0.9,en;q=0.5',

					// Marks this as our own traffic. Nothing in the response depends on it, and it
					// is not part of the cache key - it exists so the render on the other end can
					// tell it is a warm-up and decline to start another one.
					'X-Beltoft-Warm'  => '1',
				),
				'cookies'     => array(),
			)
		);

		if ( is_wp_error( $response ) || 200 !== (int) wp_remote_retrieve_response_code( $response ) ) {
			$out['failed']++;

			continue;
		}

		// nginx reports what it did with the response, and both non-MISS answers mean this
		// request did not do what a warm-up is for.
		$status = strtoupper( (string) wp_remote_retrieve_header( $response, 'x-cache' ) );

		// No X-Cache at all: there is no nginx page cache in front of this site (or the vhost lost the
		// header) - nothing was stored, so this is a failure, never a warm page.
		if ( '' === $status ) {
			$out['failed']++;

			continue;
		}

		// BYPASS: this URL can never be stored, so the skip list above is out of step with the
		// vhost - worth surfacing rather than quietly wasting a slot on it every run.
		if ( 'BYPASS' === $status ) {
			$out['bypassed']++;

			continue;
		}

		// HIT: served from cache, so PHP was not re-entered and nothing was rewritten. Counted
		// separately so the command can never again claim to have warmed a page it only read.
		if ( 'HIT' === $status ) {
			$out['cached']++;

			continue;
		}

		$out['warmed']++;
	}

	$out['seconds'] = round( microtime( true ) - $started, 1 );

	if ( ! $record ) {
		return $out;
	}

	update_option(
		BELTOFT_CACHE_LAST_WARM_OPTION,
		array(
			'time'       => time(),
			'generation' => $generation,
		) + $out,
		false
	);

	return $out;
}

/**
 * What the last warm-up did. Empty array if none has run since this was deployed.
 *
 * @return array
 */
function beltoft_cache_last_warm() {
	$last = get_option( BELTOFT_CACHE_LAST_WARM_OPTION, array() );

	return is_array( $last ) ? $last : array();
}

/**
 * The last warm-up in one line, for the admin bar and for `wp beltoft-cache status`.
 *
 * Written for the person asking "why is this page still slow" rather than for a developer: when,
 * how many pages, and - the answer that is usually the real one - whether it was cut short.
 *
 * @return string
 */
function beltoft_cache_last_warm_summary() {
	$last = beltoft_cache_last_warm();

	if ( ! $last || empty( $last['time'] ) ) {
		return __( 'ainda não correu', 'bricks' );
	}

	$when = sprintf(
		/* translators: %s: human-readable time difference, e.g. "4 minutes". */
		__( 'há %s', 'bricks' ),
		human_time_diff( (int) $last['time'] )
	);

	$what = sprintf(
		/* translators: 1: pages warmed, 2: pages already warm, 3: seconds taken. */
		__( '%1$d aquecidas, %2$d já prontas, %3$ss', 'bricks' ),
		(int) ( $last['warmed'] ?? 0 ),
		(int) ( $last['skipped'] ?? 0 ),
		(float) ( $last['seconds'] ?? 0 )
	);

	if ( ! empty( $last['superseded'] ) ) {
		$what .= __( ' - interrompido por uma alteração mais recente', 'bricks' );
	} elseif ( ! empty( $last['failed'] ) ) {
		$what .= sprintf(
			/* translators: %d: number of URLs that did not return 200. */
			__( ' - %d sem resposta', 'bricks' ),
			(int) $last['failed']
		);
	}

	return $when . ' (' . $what . ')';
}

/**
 * Remember that this request should warm the cache once it has finished answering.
 *
 * Called by the purge, so every path that empties the cache also refills it - the admin bar
 * button, a Bricks save, a product update, WP-CLI. Registering the shutdown handler once per
 * request is what keeps a single save cheap: Bricks fires save_post, woocommerce_update_product
 * and often an option write in one go, and each of those purges, but there is only ever one
 * warm-up.
 *
 * @param int $post_id The post being saved, when the caller knows it.
 */
function beltoft_cache_warm_after_response( $post_id = 0 ) {
	static $registered = false;

	/*
	 * A warm-up request must never trigger another warm-up. It cannot today - the GETs below purge
	 * nothing - but the day some hook starts purging on a front-end request, this header is the
	 * difference between a stale page and a server warming itself in a loop.
	 */
	if ( ! empty( $_SERVER['HTTP_X_BELTOFT_WARM'] ) ) {
		return;
	}

	if ( $post_id > 0 ) {
		beltoft_cache_warm_target( (int) $post_id );
	}

	if ( $registered ) {
		return;
	}

	$registered = true;

	add_action( 'shutdown', 'beltoft_cache_warm_on_shutdown', PHP_INT_MAX );
}

/**
 * The post this request should warm on top of the standing priority pages.
 *
 * @param int|null $post_id Pass an ID to set it, nothing to read it.
 * @return int
 */
function beltoft_cache_warm_target( $post_id = null ) {
	static $target = 0;

	if ( null !== $post_id ) {
		$target = (int) $post_id;
	}

	return $target;
}

/** The one URL a manual page purge should warm after the response. */
function beltoft_cache_warm_url_target( $url = null ) {
	static $target = '';

	if ( null !== $url ) {
		$target = (string) $url;
	}

	return $target;
}

/** Queue a single-page warm-up without changing the automatic full-purge policy. */
function beltoft_cache_warm_url_after_response( $url ) {
	if ( ! is_string( $url ) || '' === $url || ! empty( $_SERVER['HTTP_X_BELTOFT_WARM'] ) ) {
		return;
	}

	beltoft_cache_warm_url_target( $url );
	beltoft_cache_warm_after_response();
}

/**
 * Answer the browser, then warm.
 *
 * fastcgi_finish_request() flushes the response and closes the connection while PHP keeps running,
 * so the editor's save returns at its normal speed and the warm-up happens in the seconds after.
 * Without it the spinner would sit there for the length of the warm-up, which is precisely the cost
 * this whole mechanism exists to move off the critical path.
 *
 * Absent under WP-CLI, where there is no connection to release: a purge typed at the shell warms
 * inline and prints what it did, which is what you want from a command you are watching.
 */
function beltoft_cache_warm_on_shutdown() {
	static $done = false;

	// WP-CLI calls this directly so its result can be printed; the registered shutdown handler then
	// finds the work already done. Cheap either way, but it keeps the recorded run the real one.
	if ( $done ) {
		return;
	}

	$done = true;

	if ( function_exists( 'fastcgi_finish_request' ) ) {
		fastcgi_finish_request();
	}

	// The connection is gone by now, so nothing is waiting on this; do not let its disappearance
	// abort the warm-up half way and leave two of the three pages cold.
	ignore_user_abort( true );

	$url  = beltoft_cache_warm_url_target();
	$urls = $url ? array( $url ) : beltoft_cache_priority_urls( beltoft_cache_warm_target() );

	if ( $url ) {
		$urls = beltoft_cache_filter_urls( $urls );
		beltoft_cache_preload( false, $urls, 1, 30, 20, false ); // one page: keep the last sweep's status readable

		return;
	}

	beltoft_cache_preload( false, $urls );
}

/*
 * =============================================================================================
 * THE SWEEP AFTER A FULL PURGE
 *
 * The after-response warm-up above covers three pages; everything else was left to "warm on its
 * first visit". That only holds for visitors WITHOUT a cart: nginx never stores a response
 * rendered for a cart holder (the safety rule at the top of this file), so a shopper with
 * something in the basket got a full PHP render on every cold page, click after click, until some
 * cart-less visitor happened to open it. On staging, where the only visitor is the person testing
 * with a cart, pages simply never warmed.
 *
 * So a full purge also schedules one sweep of every preloadable URL, a minute later, run by the
 * system cron (DISABLE_WP_CRON + `wp cron event run --due-now` every minute). Same pace as the
 * warm-up - one request at a time, BELTOFT_CACHE_PRELOAD_GAP between them - so it never holds more
 * than one PHP worker. Already-warm URLs cost a stat(). A later purge bumps the generation, the
 * running sweep stands down, and that purge schedules the next one. Saving three times in a row
 * leaves one sweep queued, not three: each request queues at most one, replacing whatever was queued.
 *
 * BATCHES WITH A CURSOR. Each event handles at most BELTOFT_CACHE_SWEEP_MAX fetches in about
 * BELTOFT_CACHE_SWEEP_SECONDS (it runs inside the shared every-minute cron runner, so a long run
 * would hold back other events), then queues the next batch with its position in the URL list. Every
 * URL is tried once per generation: a page nginx refuses to store (redirect, Set-Cookie, BYPASS)
 * cannot make the sweep go round in circles, and the sweep ends at the end of the list.
 * =============================================================================================
 */

/**
 * Queue the sweep (replacing any queued one, whatever its arguments). Once per request: one save fires
 * several purge hooks. The first batch carries generation 0 = "whatever is current when it runs", so later
 * purges in the same request do not make it stale.
 */
function beltoft_cache_schedule_sweep() {
	static $queued = false;
	if ( $queued || ! empty( $_SERVER['HTTP_X_BELTOFT_WARM'] ) ) {
		return;
	}
	$queued = true;

	// wp_clear_scheduled_hook() only matches events with no arguments; sweep events carry [generation, offset].
	wp_unschedule_hook( BELTOFT_CACHE_SWEEP_HOOK );

	// A dedicated runner (`wp beltoft-cache sweep` on its own cron line) takes it: the shared runner stays free.
	if ( beltoft_cache_sweep_runner_alive() ) {
		beltoft_cache_sweep_queue_set( array( 0, 0, time() + BELTOFT_CACHE_SWEEP_DELAY ) );
		return;
	}
	wp_schedule_single_event( time() + BELTOFT_CACHE_SWEEP_DELAY, BELTOFT_CACHE_SWEEP_HOOK, array( 0, 0 ) );
}

/**
 * DEDICATED RUNNER. The sweep used to run inside the shared every-minute cron process, and its ~25 s
 * batches used up Action Scheduler's 30 s budget in that same process: queued emails went out one per
 * minute while a sweep was running. `wp beltoft-cache sweep`, on its own cron line, runs it in a process of
 * its own. While that runner has been seen recently, purges queue the sweep for it (an option, not a cron
 * event); if it stops (cron line removed), sweeps fall back to the shared runner by themselves.
 */
const BELTOFT_CACHE_SWEEP_QUEUE_OPTION  = 'beltoft_cache_sweep_queue';
const BELTOFT_CACHE_SWEEP_RUNNER_OPTION = 'beltoft_cache_sweep_runner_seen';
const BELTOFT_CACHE_SWEEP_RUNNER_BUDGET = 55;

function beltoft_cache_sweep_runner_alive() {
	wp_cache_delete( BELTOFT_CACHE_SWEEP_RUNNER_OPTION, 'options' );
	return (int) get_option( BELTOFT_CACHE_SWEEP_RUNNER_OPTION, 0 ) > time() - 5 * MINUTE_IN_SECONDS;
}

/** [generation, offset, due], or null. Read past the object cache: another process writes it. */
function beltoft_cache_sweep_queue_get() {
	wp_cache_delete( BELTOFT_CACHE_SWEEP_QUEUE_OPTION, 'options' );
	wp_cache_delete( 'notoptions', 'options' );
	$q = get_option( BELTOFT_CACHE_SWEEP_QUEUE_OPTION, null );
	return is_array( $q ) && 3 === count( $q ) ? array_map( 'intval', array_values( $q ) ) : null;
}

function beltoft_cache_sweep_queue_set( $q ) {
	if ( null === $q ) {
		delete_option( BELTOFT_CACHE_SWEEP_QUEUE_OPTION );
		return;
	}
	update_option( BELTOFT_CACHE_SWEEP_QUEUE_OPTION, array_map( 'intval', $q ), false );
}

/**
 * One batch of the sweep from $offset. Returns [generation, next offset] when there is more to do, null
 * when the sweep is finished or superseded by a newer purge.
 */
function beltoft_cache_sweep_batch( $generation = 0, $offset = 0 ) {
	// Queued for an older purge: that purge's content is gone, and its successor queued its own sweep.
	if ( $generation && (int) $generation !== beltoft_cache_generation() ) {
		return null;
	}
	$generation = $generation ? (int) $generation : beltoft_cache_generation();
	ignore_user_abort( true );

	$all   = beltoft_cache_preload_urls();
	$batch = array_slice( $all, (int) $offset );
	if ( ! $batch ) {
		return null;
	}
	$out  = beltoft_cache_preload( false, $batch, BELTOFT_CACHE_SWEEP_MAX, BELTOFT_CACHE_SWEEP_SECONDS, BELTOFT_CACHE_SWEEP_TIMEOUT );
	$next = (int) $offset + (int) $out['next'];

	if ( ! empty( $out['superseded'] ) || $next >= count( $all ) ) {
		return null;
	}
	return array( $generation, $next );
}

/**
 * The dedicated runner: batches back to back, starting a new one only while it can finish within
 * BELTOFT_CACHE_SWEEP_RUNNER_BUDGET seconds (two a minute), then the
 * next minute's run carries on. Returns how many batches ran.
 */
function beltoft_cache_sweep_run() {
	update_option( BELTOFT_CACHE_SWEEP_RUNNER_OPTION, time(), false );

	// One runner at a time (a slow minute must not overlap the next).
	if ( ! add_option( 'beltoft_cache_sweep_lock', time(), '', false ) ) {
		wp_cache_delete( 'beltoft_cache_sweep_lock', 'options' );
		if ( (int) get_option( 'beltoft_cache_sweep_lock' ) > time() - 2 * MINUTE_IN_SECONDS ) {
			return 0;
		}
		update_option( 'beltoft_cache_sweep_lock', time(), false ); // stale: its process died
	}

	// A sweep queued for the shared runner before this runner was seen: adopt it.
	$event = wp_get_scheduled_event( BELTOFT_CACHE_SWEEP_HOOK );
	if ( ! $event ) {
		foreach ( (array) _get_cron_array() as $ts => $hooks ) {
			if ( isset( $hooks[ BELTOFT_CACHE_SWEEP_HOOK ] ) ) {
				$first = reset( $hooks[ BELTOFT_CACHE_SWEEP_HOOK ] );
				$event = (object) array( 'timestamp' => $ts, 'args' => $first['args'] );
				break;
			}
		}
	}
	// A cron event only exists if a purge came while this runner was not seen, so it is newer than the queue.
	if ( $event ) {
		$args = array_values( (array) $event->args ) + array( 0, 0 );
		beltoft_cache_sweep_queue_set( array( (int) $args[0], (int) $args[1], (int) $event->timestamp ) );
		wp_unschedule_hook( BELTOFT_CACHE_SWEEP_HOOK );
	}

	$start = microtime( true );
	$ran   = 0;
	while ( microtime( true ) - $start < BELTOFT_CACHE_SWEEP_RUNNER_BUDGET - BELTOFT_CACHE_SWEEP_SECONDS ) {
		$q = beltoft_cache_sweep_queue_get();
		if ( ! $q || $q[2] > time() ) {
			break;
		}
		$next = beltoft_cache_sweep_batch( $q[0], $q[1] );
		++$ran;
		// A purge meanwhile queued a fresh sweep: leave that one alone.
		if ( beltoft_cache_sweep_queue_get() !== $q ) {
			continue;
		}
		beltoft_cache_sweep_queue_set( $next ? array( $next[0], $next[1], time() ) : null );
	}

	delete_option( 'beltoft_cache_sweep_lock' );
	return $ran;
}

add_action(
	BELTOFT_CACHE_SWEEP_HOOK,
	static function ( $generation = 0, $offset = 0 ) {
		$next = beltoft_cache_sweep_batch( $generation, $offset );
		if ( ! $next ) {
			return;
		}

		// The cron runner read the cron array when it started; other processes may have scheduled events
		// since. Re-read it from the shared object cache before writing, or their events would be dropped.
		if ( function_exists( 'wp_cache_flush_runtime' ) ) {
			wp_cache_flush_runtime();
		} else {
			wp_cache_delete( 'alloptions', 'options' );
			wp_cache_delete( 'cron', 'options' );
		}
		// This batch's own generation: if a purge landed meanwhile, the next batch sees the mismatch and stops
		// (that purge queued its own sweep).
		wp_schedule_single_event( time() + 30, BELTOFT_CACHE_SWEEP_HOOK, $next );
	},
	10,
	2
);

/**
 * Is a page cache actually in front of this site? True once nginx has written at least one entry.
 * Gates the cart-holder re-fetch: without an nginx cache every page would look "cold" forever and
 * every view by a shopper would cost a second render.
 */
function beltoft_cache_ready() {
	static $ready = null;
	if ( null !== $ready ) {
		return $ready;
	}
	$ready = false;
	$dir   = is_dir( BELTOFT_CACHE_DIR ) ? @opendir( BELTOFT_CACHE_DIR ) : false; // phpcs:ignore WordPress.PHP.NoSilentErrors
	if ( $dir ) {
		while ( false !== ( $f = readdir( $dir ) ) ) {
			if ( preg_match( '/^[0-9a-f]{32}$/', $f ) ) {
				$ready = true;
				break;
			}
		}
		closedir( $dir );
	}
	return $ready;
}

/**
 * A cart holder on a cold page: answer them, then fetch the same page anonymously so it is stored.
 *
 * Their own render can never enter the cache (it carries their cart), so without this the page stays
 * cold for them until the sweep or a cart-less visitor reaches it. The anonymous re-fetch runs after
 * the response (fastcgi_finish_request), costs one render on one worker, and only happens when the
 * page is cacheable and not on disk yet - a warm page is a cache hit and never reaches PHP at all.
 * Retail host only: the B2B hostname is never in this cache, and its path must not be mapped onto
 * the retail entry.
 */
add_action(
	'template_redirect',
	static function () {
		if ( is_admin() || wp_doing_ajax() || is_user_logged_in() || is_404() || ! empty( $_SERVER['HTTP_X_BELTOFT_WARM'] ) ) {
			return;
		}
		if ( 'GET' !== ( $_SERVER['REQUEST_METHOD'] ?? '' ) || '' !== (string) ( $_SERVER['QUERY_STRING'] ?? '' ) ) {
			return;
		}
		$has_cart = isset( $_COOKIE['woocommerce_items_in_cart'] ) || isset( $_COOKIE['woocommerce_cart_hash'] );
		foreach ( array_keys( $_COOKIE ) as $name ) {
			if ( 0 === strpos( $name, 'wp_woocommerce_session_' ) ) {
				$has_cart = true;
			}
		}
		if ( ! $has_cart ) {
			return;
		}
		$home = wp_parse_url( beltoft_cache_canonical_home_url() );
		$host = strtolower( (string) ( $_SERVER['HTTP_HOST'] ?? '' ) );
		if ( $host !== strtolower( $home['host'] ?? '' ) ) {
			return;
		}
		$url = 'https://' . $home['host'] . strtok( (string) ( $_SERVER['REQUEST_URI'] ?? '/' ), '?' );
		if ( ! beltoft_cache_filter_urls( array( $url ) ) || beltoft_cache_is_warm( $url ) || ! beltoft_cache_ready() ) {
			return;
		}
		// One re-fetch per URL per minute, however many shoppers open it at once.
		if ( ! wp_cache_add( 'refetch_' . md5( $url ), 1, 'beltoft_cache', MINUTE_IN_SECONDS ) ) {
			return;
		}
		beltoft_cache_warm_url_after_response( $url );
	},
	99
);

/**
 * Clear the recurring warm-up this plugin used to schedule.
 *
 * A purge now warms itself, so the quarter-hourly sweep has nothing left to rescue. The event
 * survives a plugin update, so it is cleared here rather than on deactivation - and only where
 * somebody is already paying for an admin request, never on a page view.
 */
add_action(
	'init',
	static function () {
		if ( ! is_admin() && ! ( defined( 'WP_CLI' ) && WP_CLI ) ) {
			return;
		}

		if ( wp_next_scheduled( BELTOFT_CACHE_PRELOAD_HOOK ) ) {
			wp_clear_scheduled_hook( BELTOFT_CACHE_PRELOAD_HOOK );
		}
	}
);

/**
 * Flush on anything that changes what a visitor would see.
 *
 * `beltoft_cache_flush` is the action other code fires - the child theme raises it when it
 * rebuilds style.min.css, because the stylesheet URL carries the file mtime as ?ver and cached
 * HTML would otherwise keep asking for the previous one.
 */
/**
 * Hooks whose first argument really is a post ID, so the revision/autosave guard applies.
 *
 * Keeping these separate is not tidiness. The guard used to run on every hook in one flat list,
 * testing $args[0] with wp_is_post_revision() - but for wp_insert_comment that argument is a
 * COMMENT id and for wp_update_nav_menu a TERM id, drawn from id sequences with nothing to do
 * with wp_posts. Whenever such an id collided with a real revision id the guard returned early
 * and the purge was silently skipped, so an approved review or a reordered menu stayed invisible
 * on every cached page for the full TTL.
 */
/**
 * Post types whose changes visitors can see. Orders (HPOS is off: shop_order is a post), coupons,
 * subscriptions and other internal types are written on every checkout - purging on those let any
 * guest empty the whole cache by placing orders, and queued a full sweep each time.
 *
 * @return string[]
 */
function beltoft_cache_purge_post_types() {
	return (array) apply_filters( 'beltoft_cache_purge_post_types', array( 'product', 'product_variation', 'page', 'post', 'bricks_template' ) );
}

/**
 * A post that was published and is not any more (draft, private, pending): its cached copy must go.
 */
add_action(
	'transition_post_status',
	static function ( $new_status, $old_status, $post ) {
		if ( 'publish' === $old_status && 'publish' !== $new_status && $post instanceof WP_Post && in_array( $post->post_type, beltoft_cache_purge_post_types(), true ) ) {
			beltoft_cache_purge_all();
		}
	},
	99,
	3
);

foreach (
	array(
		'save_post',                 // covers Bricks builder saves - they write post meta on save_post.
		'deleted_post',
		'trashed_post',
		'untrashed_post',
		'woocommerce_update_product',
	) as $hook
) {
	add_action(
		$hook,
		static function ( $post_id = 0, $post = null ) use ( $hook ) {
			// Revisions and autosaves are not published content and would flush on every
			// keystroke-triggered autosave.
			if ( $post_id && function_exists( 'wp_is_post_revision' ) && wp_is_post_revision( (int) $post_id ) ) {
				return;
			}

			if ( defined( 'DOING_AUTOSAVE' ) && DOING_AUTOSAVE ) {
				return;
			}

			// trashed_post passes the previous status as its 2nd argument; deleted_post passes the post object
			// (it is gone from the DB by then).
			$previous_status = is_string( $post ) ? $post : '';
			$post            = $post instanceof WP_Post ? $post : get_post( (int) $post_id );
			if ( ! $post || ! in_array( $post->post_type, beltoft_cache_purge_post_types(), true ) ) {
				return;
			}
			// Only changes visitors can see. Trashing: purge when it WAS published (trashed_post's 2nd argument is
			// the previous status). Everything else: when it IS published - drafts, auto-drafts, the daily trash
			// and auto-draft cleanup change nothing on the site; unpublishing is handled by transition_post_status.
			if ( 'trashed_post' === $hook ) {
				if ( 'publish' !== $previous_status ) {
					return;
				}
			} elseif ( 'publish' !== $post->post_status ) {
				return;
			}

			beltoft_cache_purge_all();

			// The one page we know for certain has changed, and the one whoever pressed save is
			// about to reload. Warmed alongside the front page and the shop archive.
			beltoft_cache_warm_after_response( (int) $post_id );
		},
		99,
		2
	);
}

/**
 * Hooks that carry no post ID at all. No guard, nothing to misread.
 *
 * bricks_global_settings is in here because Bricks keeps Settings > Custom code and the global
 * custom CSS there and regenerates that asset on update. Without it, pasting site-wide CSS or a
 * tracking snippet changed nothing on any cached page for up to the whole TTL - and since only
 * logged-in users bypass the cache, the person who made the change was the one person who could
 * see it working.
 */
foreach (
	array(
		'beltoft_cache_flush',       // explicit, from the theme or elsewhere.
		'wp_update_nav_menu',
		'switch_theme',
		'update_option_bricks_global_classes',
		'update_option_bricks_theme_styles',
		'update_option_bricks_global_variables',
		'update_option_bricks_color_palette',
		'update_option_bricks_global_settings',
	) as $hook
) {
	add_action( $hook, 'beltoft_cache_purge_all', 99 );
}

/**
 * Comments, which need a condition rather than a hook.
 *
 * `wp_insert_comment` fires for EVERY inserted comment, including ones held for moderation and
 * ones flagged as spam - and product reviews are enabled on this shop, so wp-comments-post.php
 * is a public endpoint that creates a comment row for any visitor. Purging there handed anybody
 * a way to empty the whole page cache on demand: submit reviews in a loop and the cache never
 * survives, every visitor pays the full PHP render against a pool of 5 workers, and the site is
 * slower than it was with no cache at all. Nothing is even published, so there was nothing to
 * invalidate.
 *
 * So the purge follows VISIBILITY, not insertion: a comment that is approved on the spot, and
 * any later transition into or out of approved.
 */
add_action(
	'comment_post',
	static function ( $comment_id, $approved ) {
		if ( 1 === (int) $approved && beltoft_cache_is_public_comment( $comment_id ) ) {
			beltoft_cache_purge_all();
		}
	},
	99,
	2
);

add_action(
	'transition_comment_status',
	static function ( $new_status, $old_status, $comment = null ) {
		if ( ( 'approved' === $new_status || 'approved' === $old_status ) && beltoft_cache_is_public_comment( $comment ) ) {
			beltoft_cache_purge_all();
		}
	},
	99,
	3
);

/**
 * Comments that appear on the site: blog comments and product reviews. WooCommerce order notes are
 * approved comments too (several per order) - they must not empty the cache.
 *
 * @param int|WP_Comment|null $comment Comment.
 * @return bool
 */
function beltoft_cache_is_public_comment( $comment ) {
	$comment = get_comment( $comment );
	return $comment && in_array( (string) $comment->comment_type, array( '', 'comment', 'review' ), true );
}

