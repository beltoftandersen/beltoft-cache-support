add_action(
	'admin_post_beltoft_cache_purge',
	static function () {
		if ( ! current_user_can( 'manage_options' ) ) {
			wp_die( esc_html__( 'Sem acesso.', 'bricks' ), '', array( 'response' => 403 ) );
		}

		check_admin_referer( 'beltoft_cache_purge' );

		$removed = beltoft_cache_purge_all();

		wp_safe_redirect(
			add_query_arg(
				'beltoft_cache_purged',
				(int) $removed,
				wp_get_referer() ? wp_get_referer() : admin_url()
			)
		);

		exit;
	}
);

add_action(
	'admin_post_beltoft_cache_purge_url',
	static function () {
		if ( ! current_user_can( 'manage_options' ) ) {
			wp_die( esc_html__( 'Sem acesso.', 'bricks' ), '', array( 'response' => 403 ) );
		}

		check_admin_referer( 'beltoft_cache_purge_url' );

		$url = isset( $_GET['url'] ) ? esc_url_raw( wp_unslash( $_GET['url'] ) ) : '';

		// remove_query_arg() returns a relative path when it starts from the current request URI.
		// Resolve that path on the current host before validating it; rejecting it here made the
		// admin-bar action fail even though the page URL itself was valid.
		if ( $url && ! wp_parse_url( $url, PHP_URL_HOST ) ) {
			$url = home_url( '/' . ltrim( $url, '/' ) );
		}

		$home_host = wp_parse_url( beltoft_cache_canonical_home_url(), PHP_URL_HOST );
		$url_host  = wp_parse_url( $url, PHP_URL_HOST );

		if ( ! $url || ! $url_host || strtolower( $url_host ) !== strtolower( $home_host ) ) {
			wp_die( esc_html__( 'Esta página não pode ser limpa.', 'bricks' ), '', array( 'response' => 400 ) );
		}

		$removed = beltoft_cache_purge_url( $url );
		beltoft_cache_warm_url_after_response( $url );
		$redirect = wp_get_referer() ? wp_get_referer() : home_url( '/' );

		wp_safe_redirect(
			add_query_arg(
				'beltoft_cache_purged_url',
				$removed ? '1' : '0',
				$redirect
			)
		);

		exit;
	}
);

